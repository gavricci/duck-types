import { fileURLToPath } from 'node:url';
import { expect, test } from 'vitest';
import { generate } from '../src/generate/index.js';
import { scanSource } from '../src/generate/scan.js';

const fixtures = fileURLToPath(new URL('./fixtures/', import.meta.url));

test('scanSource finds literal sql() calls bound to duck-types', () => {
  const found = scanSource(
    `import { sql, sql as q } from 'duck-types';\nconst a = sql('x');\nconst b = q(\`y\`);\nconst c = sql(\`\${1}\`);\nconst d = other('z');`,
    'f.ts',
  );
  expect(found.map((f) => [f.text, f.line, f.column])).toEqual([
    ['x', 2, 15],
    ['y', 3, 13],
  ]);
});

test('generate emits declarations and diagnostics', async () => {
  const result = await generate({
    include: ['app.ts'],
    cwd: fixtures,
    init: `${fixtures}schema.sql`,
  });
  expect(result.queries).toHaveLength(4);
  expect(result.diagnostics.map((d) => [d.query.line, d.message])).toEqual([
    [11, 'cannot infer the type of parameter $x; add a cast, e.g. $x::integer'],
    [12, expect.stringContaining('nope')],
  ]);
  expect(result.declarations).toMatchInlineSnapshot(`
    "// Generated by duck-types. Do not edit.
    import type { JS } from '@duckdb/node-api';

    declare module 'duck-types' {
      interface Queries {
        "select\\n  count(*) as n\\nfrom users": {
          row: { n: bigint | null };
          params: [];
        };
        "select $x as x": {
          row: { unknown: unknown };
          params: { x: unknown };
        };
        "select id, name from users where id = $id": {
          row: { id: number | null; name: string | null };
          params: { id: number | null };
        };
      }
    }
    "
  `);
});
